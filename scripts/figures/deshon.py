TAIL = {' 입니다': '이다', '입니다': '이다', '합니다': '한다', '됩니다': '된다'}

def convert(text):
    # protect fenced code and inline code
    blocks = []
    def hide(m):
        blocks.append(m.group(0)); return f'\x00{len(blocks)-1}\x00'
    t = re.sub(r'```.*?```|`[^`\n]*`|<svg\b.*?</svg>', hide, text, flags=re.S)
    for k in sorted(M, key=len, reverse=True):
        t = t.replace(k, M[k])
    for k in sorted(TAIL, key=len, reverse=True):
        t = t.replace(k, TAIL[k])
    return re.sub(r'\x00(\d+)\x00', lambda m: blocks[int(m.group(1))], t)

